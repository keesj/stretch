/**
 * The stretch sync journal. State on a device = replay(legacy, ops):
 * the frozen legacy base (progress from before this build) plus the op
 * journal. Ops are immutable and idempotent (deduped by `id` on merge),
 * so sync is a matter of exchanging unseen ops.
 */

export type EntityKind =
  | "plankDay"
  | "challenge"
  | "session"
  | "settings"
  | "profile"
  | "trophyCase"
  | "reset";

export type OpKind = "create" | "patch";

/**
 * The sync identity of the legacy self-start challenge. Its ops and
 * projection blob predate multi-challenge sync and keep this id so
 * existing journals stay valid.
 */
export const LEGACY_PLANK_SYNC_ID = "plank";

/** Shape of a challenge sync id (also the bound for op.entityId). */
export const SYNC_ID_RE = /^[a-z0-9][a-z0-9-]{0,63}$/i;

/**
 * The localStorage projection blob of a challenge: the legacy challenge
 * keeps the historical "plankChallenge" key, all others use
 * "challenge:<syncId>".
 */
export function challengeBlobKey(
  syncId: string
): "plankChallenge" | `challenge:${string}` {
  return syncId === LEGACY_PLANK_SYNC_ID ? "plankChallenge" : `challenge:${syncId}`;
}

export interface Op {
  // Idempotency key (UUIDv4, generated by the creating device)
  id: string;
  // Hybrid logical clock, sortable string (see hlc.ts)
  hlc: string;
  // Device that created the op; breaks ties between equal clocks
  device: string;
  entity: EntityKind;
  // plankDay: YYYY-MM-DD (the challenge is in data.challengeId; ops
  // without one belong to the legacy "plank") · challenge: the challenge's
  // syncId · session: session id · settings: "app" · profile: "me" ·
  // trophyCase: "me" · reset: "all"
  entityId: string;
  kind: OpKind;
  data?: Record<string, unknown>;
}

/**
 * The account's display identity for the squad (social) views: the name
 * and avatar people see in the standings and on the trophy chamber.
 * Synced like settings (last-write-wins per field), never cleared by a
 * reset (it is identity, not progress).
 */
export interface Profile {
  name: string;
  avatar: string;
}

export const DEFAULT_PROFILE: Profile = { name: "", avatar: "" };

/**
 * One item placed on the chamber shelf at a free position. x/y are
 * percentages of the shelf canvas (0..100), so the layout scales with the
 * screen. Items may overlap — the shelf is a little diorama, not a grid.
 */
export interface PlacedItem {
  /** A trophy id or a free-decoration id. */
  item: string;
  /** Horizontal position, percent of the shelf width (0..100). */
  x: number;
  /** Vertical position, percent of the shelf height (0..100). */
  y: number;
  /**
   * 1 = normal, 2 = grown (double-tapped). A grown item renders twice as
   * large and draws twice the points. Older ops omit it: normal.
   */
  size: 1 | 2;
}

/** The shelf can hold this many placed items at once. */
export const MAX_ITEMS = 24;

/**
 * The trophy chamber's decoration: the chosen background theme and the
 * placed items. Only the user's *choices* are synced — the trophies
 * themselves are always derived from the ops, so a case can never show a
 * trophy that was not earned.
 *
 * Older ops carried `slots` (a compact list of ids, then a 4x4 grid with
 * nulls); the replay normalizes both to free-position `items`.
 */
export interface TrophyCaseState {
  /** A background theme id (see TROPHY_BACKGROUNDS). */
  background: string;
  /** Placed items at free positions (overlap allowed). */
  items: PlacedItem[];
}

export const DEFAULT_TROPHY_CASE: TrophyCaseState = { background: "classic", items: [] };

/**
 * Progress from before the sync build, frozen into localStorage once on
 * upgrade. It acts as the base layer of the replay and is never pushed to
 * the server (it stays on this device).
 */
export interface LegacyBase {
  plank: { startedAt: string | null; days: { date: string; seconds: number }[] };
  sessions: { id: string; routineId: string; routineTitle: string; duration: number; completedAt: string }[];
  settings: {
    theme: "light" | "dark" | "system";
    soundEnabled: boolean;
    hapticEnabled: boolean;
    // A base frozen by an older build lacks the notification fields;
    // replay fills them from the defaults.
    notificationsEnabled?: boolean;
    remindEnabled?: boolean;
    remindTime?: string;
  };
  profile: Profile;
  trophyCase: TrophyCaseState;
}

/** One op's server-side rejection reason (returned with a 400 push). */
export interface InvalidOp {
  id: string;
  error: string;
}

/**
 * The social feed: one entry per account in the group, raw seconds only.
 * The server derives this from stored ops (last-write-wins profile,
 * best hold per day) and never returns today's or future dates — the
 * quiet-day rule. Points/ranks are computed by the client, which owns the
 * scoring rules.
 */
export interface SocialMember {
  accountId: string;
  name: string;
  avatar: string;
  startedAt: string | null;
  days: { date: string; seconds: number }[];
}

export interface StandingsFeed {
  /** The server's local date (YYYY-MM-DD); everything before it is public. */
  asOf: string;
  roster: SocialMember[];
}

/**
 * A squad: a named group of accounts. Squads are managed server-side
 * (admin CLI only) — they scope the social standings and are what gate
 * the Squad and Chamber nav tabs in the app.
 */
export interface Squad {
  id: string;
  name: string;
}
